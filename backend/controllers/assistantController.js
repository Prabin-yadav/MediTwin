const AiChat = require("../models/AiChat");
const aiProviderManager = require("../services/ai/AIProviderManager");
const patientContextService = require("../services/patientContextService");

/**
 * Builds the strict clinical system prompt combining AI safety directives and patient context
 */
function buildSystemPrompt(patientContextText) {
  return `You are the MediTwin AI Health Assistant, a professional, empathetic, and reliable health-information and clinical decision-support companion.
Your primary role is to help the patient understand their verified MediTwin health data, lab test results, acute-risk scores, and symptom differentials in plain, reassuring language.

CLINICAL & SAFETY DIRECTIVES (MANDATORY):
1. DECISION SUPPORT ONLY: You are an educational decision-support assistant, NOT a doctor.
2. VERIFIED DATA GROUNDING: Base answers on the verified patient context provided below. Always distinguish between what is directly recorded in MediTwin records (e.g., "According to your recorded lab results...", "Your 90-day risk assessment calculated...") and general clinical context.
3. NEVER INDEPENDENTLY DIAGNOSE: Do not independently diagnose conditions. You may explain results and probabilities already computed by MediTwin's clinical modules, but clearly state that these are machine learning estimates requiring physician confirmation.
4. TREATMENT PLAN & MEDICATIONS EXPLANATION:
   - When the patient asks about medications, medicines, or treatment options from their generated MediTwin treatment plan, YOU MUST EXPLAIN AND LIST the specific medication classes and common medicine examples generated by Module 3 for their identified conditions (e.g., Biguanides like Metformin for glycemic control, ACE inhibitors/ARBs for blood pressure, etc.), as well as any first-line lifestyle/non-pharmacological approaches.
   - Always clarify that these medication classes and candidates are algorithmic decision-support recommendations generated by MediTwin to discuss with their licensed physician, NOT a self-prescription.
   - Advise them to consult their doctor or pharmacist before starting, stopping, or altering any medication.
5. DATA LIMITATIONS: If data or specific lab values are missing or incomplete, clearly state that rather than assuming or guessing.
6. EMERGENCY PROTOCOL: If the patient describes severe, acute red-flag symptoms (e.g., crushing chest pain, difficulty breathing, sudden one-sided numbness/weakness, severe bleeding, or loss of consciousness), immediately and prominently advise them to seek emergency medical care (call 911 / 112 or visit the nearest ER) without delay.
7. CLINICIAN CONSULTATION: For any diagnosis, treatment changes, persistent symptoms, or clinical questions, advise the patient to consult a qualified healthcare professional.
8. CLARITY & BREVITY: Provide structured, concise, and easy-to-read responses (use brief bullet points where helpful). Avoid technical jargon without explanation.

--- PATIENT CLINICAL DATA FROM MEDITWIN ---
${patientContextText}
------------------------------------------`;
}

// POST /api/assistant/chat
const chatWithAssistant = async (req, res) => {
  try {
    const { patientId } = req.user;
    if (!patientId) {
      return res.status(400).json({ message: "No patient ID found on authenticated account." });
    }

    const rawMessage = req.body.message;
    if (!rawMessage || typeof rawMessage !== "string" || !rawMessage.trim()) {
      return res.status(400).json({ message: "A question or message is required." });
    }

    const message = rawMessage.trim();
    if (message.length > 1200) {
      return res.status(400).json({ message: "Message exceeds maximum length of 1200 characters." });
    }

    // 1. Retrieve targeted patient context (token-efficient)
    const contextResult = await patientContextService.buildContextForQuery(patientId, message);
    const systemPrompt = buildSystemPrompt(contextResult.formattedText);

    // 2. Fetch recent conversation history to provide short-term context (last 6 messages max)
    const existingChat = await AiChat.findOne({ patientId });
    const previousMessages = existingChat?.messages ? existingChat.messages.slice(-6) : [];

    // Format messages for LLM
    const formattedMessages = previousMessages.map((m) => ({
      role: m.role,
      content: m.content,
    }));
    formattedMessages.push({ role: "user", content: message });

    // 3. Call AIProviderManager (Sequential fallback: Gemini -> OpenRouter -> Groq)
    const completion = await aiProviderManager.generateResponse(systemPrompt, formattedMessages);

    // 4. Persist messages in AiChat history
    const userMsg = {
      role: "user",
      content: message,
      createdAt: new Date(),
    };
    const assistantMsg = {
      role: "assistant",
      content: completion.text,
      provider: completion.provider,
      model: completion.model,
      createdAt: new Date(),
    };

    if (existingChat) {
      existingChat.messages.push(userMsg, assistantMsg);
      // Keep chat history capped at last 50 messages to manage MongoDB document size
      if (existingChat.messages.length > 50) {
        existingChat.messages = existingChat.messages.slice(-50);
      }
      await existingChat.save();
    } else {
      await AiChat.create({
        patientId,
        messages: [userMsg, assistantMsg],
      });
    }

    return res.json({
      reply: completion.text,
      provider: completion.provider,
      model: completion.model,
      timestamp: assistantMsg.createdAt,
    });
  } catch (err) {
    console.error("[AssistantController] Error in chatWithAssistant:", err.message);

    if (err.code === "NO_PROVIDERS_CONFIGURED") {
      return res.status(503).json({
        message: "AI Health Assistant is currently unconfigured. Please add an API key (GEMINI_API_KEY, OPENROUTER_API_KEY, or GROQ_API_KEY) in the backend configuration.",
        code: "NO_PROVIDERS_CONFIGURED",
      });
    }

    if (err.code === "ALL_PROVIDERS_FAILED") {
      return res.status(503).json({
        message: "The AI Health Assistant is temporarily busy across all available providers. Please try again in a few moments.",
        code: "ALL_PROVIDERS_FAILED",
      });
    }

    return res.status(500).json({
      message: "An unexpected error occurred while processing your question with the AI assistant. Please try again shortly.",
    });
  }
};

// GET /api/assistant/history
const getHistory = async (req, res) => {
  try {
    const { patientId } = req.user;
    const chat = await AiChat.findOne({ patientId }).lean();
    return res.json({
      messages: chat?.messages || [],
    });
  } catch (err) {
    console.error("[AssistantController] getHistory error:", err);
    return res.status(500).json({ message: "Failed to load chat history." });
  }
};

// DELETE /api/assistant/history
const clearHistory = async (req, res) => {
  try {
    const { patientId } = req.user;
    await AiChat.deleteOne({ patientId });
    return res.json({ success: true, message: "Conversation history cleared." });
  } catch (err) {
    console.error("[AssistantController] clearHistory error:", err);
    return res.status(500).json({ message: "Failed to clear chat history." });
  }
};

// GET /api/assistant/prompts
const getSuggestedPrompts = async (req, res) => {
  try {
    const { patientId } = req.user;
    const summary = await patientContextService.getHealthSummary(patientId);

    const prompts = [];

    if (summary.latestAcuteRisk && !summary.latestAcuteRisk.includes("No acute risk")) {
      prompts.push("Explain my 90-day acute event risk score and key drivers");
    }
    if (summary.latestDifferential && !summary.latestDifferential.includes("No symptom differential")) {
      prompts.push("What does my symptom differential diagnosis result indicate?");
    }
    if (summary.treatmentUrgency && !summary.treatmentUrgency.includes("No active treatment")) {
      prompts.push("Summarize my personalized treatment and dietary recommendations");
    }

    // Baseline fallbacks
    prompts.push("What do my latest lab test results mean?");
    prompts.push("What lifestyle steps can I take to improve my health scores?");
    prompts.push("What questions should I ask my doctor at my next visit?");

    // Limit to top 4 unique prompts
    const uniquePrompts = Array.from(new Set(prompts)).slice(0, 4);

    return res.json({ prompts: uniquePrompts });
  } catch (err) {
    console.error("[AssistantController] getSuggestedPrompts error:", err);
    return res.json({
      prompts: [
        "Explain my latest health results",
        "What do my lab tests mean?",
        "What lifestyle habits should I focus on?",
        "What should I discuss with my doctor?",
      ],
    });
  }
};

module.exports = {
  chatWithAssistant,
  getHistory,
  clearHistory,
  getSuggestedPrompts,
};
